export type EmojiMatch = { name: string; emoji: string };

/** Prefix search (then substring), most relevant first. */
export function searchEmoji(query: string, limit = 8): EmojiMatch[] {
  const q = query.toLowerCase();
  if (!q) return [];
  const matches: EmojiMatch[] = [];
  for (const [name, emoji] of Object.entries(EMOJI)) {
    if (name.startsWith(q)) matches.push({ name, emoji });
  }
  matches.sort((a, b) => a.name.length - b.name.length);
  if (matches.length < limit) {
    for (const [name, emoji] of Object.entries(EMOJI)) {
      if (!name.startsWith(q) && name.includes(q)) matches.push({ name, emoji });
      if (matches.length >= limit) break;
    }
  }
  return matches.slice(0, limit);
}

/** Exact shortcode lookup, e.g. "sob" -> "😭". */
export function exactEmoji(name: string): string | null {
  return EMOJI[name.toLowerCase()] ?? null;
}
